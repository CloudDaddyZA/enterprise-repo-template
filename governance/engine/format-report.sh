#!/usr/bin/env bash
# ============================================================================
# Governance Engine - Compliance Report Formatter
# ============================================================================
# Converts a JSON compliance report to Markdown format suitable for
# GitHub Issues, PR comments, or wiki pages.
#
# Usage: ./format-report.sh <report.json> [output-format]
#   output-format: markdown (default), json-summary, badge
#
# Requires: jq
# ============================================================================
set -euo pipefail

REPORT_FILE="${1:?Usage: format-report.sh <report.json> [format]}"
FORMAT="${2:-markdown}"

if [ ! -f "$REPORT_FILE" ]; then
  echo "❌ Report file not found: $REPORT_FILE" >&2
  exit 1
fi

command -v jq >/dev/null 2>&1 || { echo "❌ jq not found" >&2; exit 1; }

# --------------------------------------------------------------------------
# Extract report data
# --------------------------------------------------------------------------
REPO=$(jq -r '.report.repository' "$REPORT_FILE")
PROFILE=$(jq -r '.report.profile' "$REPORT_FILE")
TIMESTAMP=$(jq -r '.report.timestamp' "$REPORT_FILE")
SCORE=$(jq '.report.score' "$REPORT_FILE")
TOTAL=$(jq '.report.summary.total_checks' "$REPORT_FILE")
PASSED=$(jq '.report.summary.passed' "$REPORT_FILE")
FAILED=$(jq '.report.summary.failed' "$REPORT_FILE")
WARNINGS=$(jq '.report.summary.warnings' "$REPORT_FILE")

# --------------------------------------------------------------------------
# Badge format
# --------------------------------------------------------------------------
if [ "$FORMAT" = "badge" ]; then
  if [ "$SCORE" -ge 90 ]; then
    COLOR="brightgreen"
  elif [ "$SCORE" -ge 70 ]; then
    COLOR="yellow"
  elif [ "$SCORE" -ge 50 ]; then
    COLOR="orange"
  else
    COLOR="red"
  fi
  echo "![Compliance](https://img.shields.io/badge/compliance-${SCORE}%25-${COLOR})"
  exit 0
fi

# --------------------------------------------------------------------------
# JSON summary format
# --------------------------------------------------------------------------
if [ "$FORMAT" = "json-summary" ]; then
  jq '{
    repository: .report.repository,
    profile: .report.profile,
    score: .report.score,
    timestamp: .report.timestamp,
    passed: .report.summary.passed,
    failed: .report.summary.failed,
    warnings: .report.summary.warnings
  }' "$REPORT_FILE"
  exit 0
fi

# --------------------------------------------------------------------------
# Markdown format
# --------------------------------------------------------------------------
if [ "$SCORE" -ge 90 ]; then
  BADGE="🟢"
  STATUS="Compliant"
elif [ "$SCORE" -ge 70 ]; then
  BADGE="🟡"
  STATUS="Partially Compliant"
else
  BADGE="🔴"
  STATUS="Non-Compliant"
fi

cat <<EOF
# $BADGE Governance Compliance Report

| Field | Value |
|-------|-------|
| **Repository** | \`$REPO\` |
| **Profile** | \`$PROFILE\` |
| **Score** | **${SCORE}%** — $STATUS |
| **Assessed** | $TIMESTAMP |

## Summary

| Metric | Count |
|--------|-------|
| Total Checks | $TOTAL |
| ✅ Passed | $PASSED |
| ❌ Failed | $FAILED |
| ⚠️ Warnings | $WARNINGS |

## Findings

### ❌ Failed Checks

| Category | Check | Message | Remediation |
|----------|-------|---------|-------------|
$(jq -r '.report.findings[] | select(.status == "fail") | "| \(.category) | \(.check) | \(.message) | \(.remediation) |"' "$REPORT_FILE")

### ⚠️ Warnings

| Category | Check | Message |
|----------|-------|---------|
$(jq -r '.report.findings[] | select(.status == "warn") | "| \(.category) | \(.check) | \(.message) |"' "$REPORT_FILE")

### ✅ Passed Checks

| Category | Check | Message |
|----------|-------|---------|
$(jq -r '.report.findings[] | select(.status == "pass") | "| \(.category) | \(.check) | \(.message) |"' "$REPORT_FILE")

---

*Generated by the Governance Engine on $TIMESTAMP*
EOF
